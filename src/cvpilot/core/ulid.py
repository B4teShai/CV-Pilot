"""ULID generation: 48-bit millisecond timestamp plus 80 random bits, Crockford base32.

Ids generated by one process are strictly increasing: within one millisecond, or when the
clock steps backwards, the random part of the previous id is incremented instead of redrawn.
"""

from __future__ import annotations

import re
import secrets
import threading
import time

_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
_DECODE = {c: i for i, c in enumerate(_ALPHABET)}
_VALID = re.compile(r"[0-9A-HJKMNP-TV-Z]{26}")
_RAND_BITS = 80
_RAND_MAX = (1 << _RAND_BITS) - 1
_TIME_MAX = (1 << 48) - 1

_lock = threading.Lock()
_last_ms = -1
_last_rand = 0


def _encode(value: int) -> str:
    chars = []
    for _ in range(26):
        chars.append(_ALPHABET[value & 31])
        value >>= 5
    return "".join(reversed(chars))


class UlidGenerator:
    """Thread-safe monotonic ULID source; one instance keeps one ordering."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._last_ms = -1
        self._last_rand = 0

    def generate(self, now_ms: int | None = None) -> str:
        """Return a new ULID; ``now_ms`` overrides the clock (tests)."""
        ms = time.time_ns() // 1_000_000 if now_ms is None else now_ms
        with self._lock:
            if ms <= self._last_ms:
                ms = self._last_ms
                rand = self._last_rand + 1
                if rand > _RAND_MAX:
                    ms += 1
                    rand = secrets.randbits(_RAND_BITS)
            else:
                rand = secrets.randbits(_RAND_BITS)
            if ms > _TIME_MAX:
                raise OverflowError("ULID timestamp exceeds 48 bits")
            self._last_ms, self._last_rand = ms, rand
        return _encode((ms << _RAND_BITS) | rand)


_default = UlidGenerator()


def generate_ulid(now_ms: int | None = None) -> str:
    """Return a new ULID from the process-wide generator."""
    return _default.generate(now_ms)


def is_valid_ulid(value: object) -> bool:
    """True for a 26-character Crockford base32 string that fits in 128 bits."""
    return isinstance(value, str) and _VALID.fullmatch(value) is not None and value[0] <= "7"


def ulid_timestamp_ms(value: str) -> int:
    """Millisecond timestamp encoded in a valid ULID."""
    if not is_valid_ulid(value):
        raise ValueError("not a valid ULID")
    number = 0
    for char in value[:10]:
        number = (number << 5) | _DECODE[char]
    return number
